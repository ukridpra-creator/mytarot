function reduceNumberToDigit(numStr) {
  var digits = numStr.replace(/[^0-9]/g, '');
  if (!digits) return null;
  var sum = digits.split('').reduce(function(a, b) { return a + parseInt(b, 10); }, 0);
  while (sum > 9) {
    sum = String(sum).split('').reduce(function(a, b) { return a + parseInt(b, 10); }, 0);
  }
  return sum === 0 ? 9 : sum; // เลข 0 ล้วนๆ ให้ตกไปที่พลังงานเลข 9 (การสิ้นสุด/เริ่มใหม่)
}

