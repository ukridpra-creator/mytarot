  if (gender === 'male') {
    return BRAHMA_POSITIONS[offset];
  } else {
    // นับซ้าย = ทวนเข็ม = 12 - offset
    const idx = offset === 0 ? 0 : (12 - offset);
    return BRAHMA_POSITIONS[idx];
  }
