// ─── คำนวณตรีวัย ───
function calcTriwai(dateStr) {
  var jsDay = new Date(dateStr + 'T12:00:00').getDay(); // 0=อา
  var order = TRIWAI_ORDER[jsDay]; // [ปฐม, มัชฌิม, ปัจฉิม] = planet index

  var vais = [];
  for (var v = 0; v < 3; v++) {
    var pIdx = order[v]; // 0-6
    var isOwnDay = (pIdx === jsDay); // ดาวเดียวกับวันเกิด
    var data = TRIWAI_DATA[pIdx][v];
    vais.push({
      vaiIdx:     v,
      vaiName:    VAI_NAMES[v],
      vaiAge:     VAI_AGE[v],
      vaiEmoji:   VAI_EMOJI[v],
      planetIdx:  pIdx,
      planetName: TRIWAI_PLANET[pIdx],
      isOwnDay:   isOwnDay,
      title:      data.title,
      text:       data.text
    });
  }

  return {
    dateStr:   dateStr,
    jsDay:     jsDay,
    dayName:   TRIWAI_DAY_NAME[jsDay],
    planetName:TRIWAI_PLANET[jsDay],
    vais:      vais
  };
}
