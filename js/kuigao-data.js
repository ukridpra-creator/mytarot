// ─── ดาวประจำตัว จากปีเกิด ───
// ดาวลดลงทีละ 1 ทุกปี วนซ้ำ 1-9
// ปี 2569 (2026) = ดาว 3
function getPersonalStar(year) {
  // base: ปี 2569 = ดาว 3
  var diff = 2026 - year;
  var star = ((3 + diff) % 9);
  if (star === 0) star = 9;
  return star;
}

