// ─── วางดาวใน Lo Shu จาก center ───
// Lo Shu order: SE=4 S=9 SW=2 E=3 C=5 W=7 NE=8 N=1 NW=6
// เมื่อ center=5: SE=4,S=9,SW=2,E=3,C=5,W=7,NE=8,N=1,NW=6
// offset แต่ละตำแหน่ง
var POSITION_OFFSET = {
  SE:  -1, S:   4, SW: -3,
  E:  -2,  C:   0, W:  2,
  NE:  3,  N:  -4, NW:  1,
};

function getGridStars(centerStar) {
  var grid = {};
  Object.keys(POSITION_OFFSET).forEach(function(pos) {
    var star = ((centerStar + POSITION_OFFSET[pos] - 1 + 9) % 9) + 1;
    grid[pos] = star;
  });
  return grid;
}

