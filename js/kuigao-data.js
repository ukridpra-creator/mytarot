// ─── หาตำแหน่งของดาวประจำตัวในปีนี้ ───
function getPersonalStarPosition(personalStar, grid) {
  var pos = 'C';
  Object.keys(grid).forEach(function(p) {
    if (grid[p] === personalStar) pos = p;
  });
  return pos;
}

// ─── MAIN FUNCTION ───
function calcKuigao(birthYear, currentYear) {
  var personalStar = getPersonalStar(birthYear);
  var centerStar = CENTER_STAR[currentYear] || CENTER_STAR[2569];
  var grid = getGridStars(centerStar);
  var personalPos = getPersonalStarPosition(personalStar, grid);

  // หาทิศมงคล (ดาว 1,4,6,8,9)
  var luckyDirs = [];
  var unluckyDirs = [];
  Object.keys(grid).forEach(function(pos) {
    if (pos === 'C') return;
    var star = grid[pos];
    if (STAR_INFO[star].lucky) luckyDirs.push({ pos:pos, star:star });
    else unluckyDirs.push({ pos:pos, star:star });
  });

  return {
    birthYear, currentYear,
    personalStar,
    personalStarInfo: STAR_INFO[personalStar],
    centerStar,
    centerStarInfo: STAR_INFO[centerStar],
    grid,
    personalPos,
    personalPosInfo: PERSONAL_STAR_POSITION[personalPos],
    luckyDirs,
    unluckyDirs,
  };
}

