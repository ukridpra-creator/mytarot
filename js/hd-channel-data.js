// helper function ค้นหา channel จาก gate numbers
function findChannelByGates(gate1, gate2) {
  return HD_CHANNELS.find(ch => {
    const gates = ch.gates.split('-').map(Number);
    return (gates[0] === gate1 && gates[1] === gate2) || (gates[0] === gate2 && gates[1] === gate1);
  });
}
