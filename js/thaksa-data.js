// ─── คำนวณยาม ───
function getYam(hour) {
  // ยาม 7 = 00-03, ยาม 8 = 03-06, ยาม 1 = 06-09...
  if (hour >= 6 && hour < 9)  return 1;
  if (hour >= 9 && hour < 12) return 2;
  if (hour >= 12 && hour < 15) return 3;
  if (hour >= 15 && hour < 18) return 4;
  if (hour >= 18 && hour < 21) return 5;
  if (hour >= 21) return 6;
  if (hour >= 0 && hour < 3)  return 7;
  return 8; // 03-06
}

// คำนวณดาวเจ้ายาม
function getYamPlanet(dayOfWeek, yam) {
  var startPlanet = DAY_START_PLANET[dayOfWeek]; // 1-7
  var planetIdx = ((startPlanet - 1 + (yam - 1)) % 7);
  return planetIdx + 1; // 1-7
}

