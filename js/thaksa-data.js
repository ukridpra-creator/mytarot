// หมายเหตุ: กาลกิณี (ทิศ 8) = ดาวราหู/เสาร์ เสมอ ขึ้นอยู่กับตำรา

// หาว่าดาวยามตกอยู่ในทิศไหน
function getThitOfPlanet(dayOfWeek, planetNum) {
  var order = DAY_THIT[dayOfWeek];
  for (var t = 0; t < order.length; t++) {
    if (order[t] === planetNum) return t; // 0-7
  }
  return 7; // กาลกิณี default
}

