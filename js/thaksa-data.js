// ─── คำนวณทักษา ───
function calcThaksa(dateStr, hour) {
  var jsDay = new Date(dateStr + 'T12:00:00').getDay(); // 0=อา
  var h = (hour !== undefined && hour !== null) ? hour : 12;
  var yam = getYam(h);
  var yamPlanet = getYamPlanet(jsDay, yam); // 1-7

  // ทิศของดาวเจ้าวัน (ดาวประจำวัน)
  var dayPlanet = jsDay + 1; // 1-7 (อา=1 ... ส=7)
  var dayThit = getThitOfPlanet(jsDay, dayPlanet); // 0-7

  // ทิศของดาวเจ้ายาม
  var yamThit = getThitOfPlanet(jsDay, yamPlanet); // 0-7

  // สร้างข้อมูลทิศทั้ง 8
  var thits = [];
  var order = DAY_THIT[jsDay];
  for (var t = 0; t < 8; t++) {
    var planet = order[t];
    var isDay = (planet === dayPlanet);
    var isYam = (planet === yamPlanet);
    var data = THAKSA_DATA[planet] ? THAKSA_DATA[planet][t] : null;
    thits.push({
      thitIdx:  t,
      thitName: THIT_NAMES[t],
      thitEmoji:THIT_EMOJI[t],
      planet:   planet,
      planetName: PLANET_NAME[planet] || 'ราหู',
      isDay:    isDay,
      isYam:    isYam,
      title:    data ? data.title : '',
      text:     data ? data.text : ''
    });
  }

  return {
    dateStr:    dateStr,
    jsDay:      jsDay,
    dayName:    DAY_NAME[jsDay],
    dayPlanet:  dayPlanet,
    dayPlanetName: PLANET_NAME[dayPlanet],
    hour:       h,
    yam:        yam,
    yamPlanet:  yamPlanet,
    yamPlanetName: PLANET_NAME[yamPlanet],
    dayThit:    dayThit,
    yamThit:    yamThit,
    thits:      thits
  };
}