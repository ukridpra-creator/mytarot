// ─── คำนวณ Nakshatra จากวันเดือนปี ───
// ใช้ Julian Day Number แบบง่าย
function getNakshatraIndex(day, month, year) {
  // คำนวณ Moon's longitude แบบ approximate
  // ใช้สูตรง่ายๆ สำหรับ demo
  var a = Math.floor((14 - month) / 12);
  var y = year + 4800 - a;
  var m = month + 12 * a - 3;
  var jdn = day + Math.floor((153 * m + 2) / 5) + 365 * y + Math.floor(y / 4) - Math.floor(y / 100) + Math.floor(y / 400) - 32045;

  // Moon cycle ~ 27.32 days per nakshatra cycle
  var moonLong = ((jdn * 13.176358) % 360 + 360) % 360;
  var idx = Math.floor(moonLong / (360 / 27));
  return idx % 27;
}

