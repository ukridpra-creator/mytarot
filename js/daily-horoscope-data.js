// คำนวณราศีจันทร์วันนี้แบบ tropical (ระบบราศีตะวันตกทั่วไป) — แยกจาก moon-engine.js ที่คำนวณแบบ sidereal สำหรับเวทิก
function getMoonTropicalSign(year, month, day, hour, minute) {
  hour = hour || 6; minute = minute || 0;
  var date = new Date(Date.UTC(year, month - 1, day, hour - 7, minute, 0)); // UTC+7 Bangkok
  var moonPos = Astronomy.EclipticGeoMoon(date);
  var lon = ((moonPos.lon % 360) + 360) % 360;
  return Math.floor(lon / 30); // 0=เมษ ... 11=มีน
}

// ระยะห่างราศี (0-6) ระหว่างราศีเกิดกับราศีจันทร์วันนี้
function getAspectIndex(userSignIdx, moonSignIdx) {
  var diff = Math.abs(userSignIdx - moonSignIdx) % 12;
  return Math.min(diff, 12 - diff);
}

function getDayOfYear(d) {
  var start = new Date(d.getFullYear(), 0, 0);
  var diff = d - start;
  return Math.floor(diff / 86400000);
}

// ดึงคำทำนายวันนี้สำหรับราศีที่เลือก
function getDailyHoroscope(userSignIdx, today) {
  today = today || new Date();
  var moonSignIdx = getMoonTropicalSign(today.getFullYear(), today.getMonth() + 1, today.getDate());
  var aspectIdx = getAspectIndex(userSignIdx, moonSignIdx);
  var aspect = ASPECT_INFO[aspectIdx];
  var versionIdx = getDayOfYear(today) % 3;
  var msgs = ASPECT_MEANINGS[aspectIdx];

  return {
    userSign: ZODIAC_TH[userSignIdx],
    userSignEmoji: ZODIAC_EMOJI[userSignIdx],
    moonSign: ZODIAC_TH[moonSignIdx],
    aspectName: aspect.th,
    stars: aspect.stars,
    work: msgs.work[versionIdx],
    money: msgs.money[versionIdx],
    love: msgs.love[versionIdx],
    health: msgs.health[versionIdx]
  };
}
