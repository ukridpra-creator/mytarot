// helper: หาไพ่จาก id
function getDreamCard(id) {
  return DREAM_CARDS.find(c => c.id === id) || null;
}

// helper: เช็ค combo (3+ ใบจากหมวดเดียวกัน)
function getDreamCombo(cards) {
  const counts = {};
  cards.forEach(c => { counts[c.category] = (counts[c.category]||0) + 1; });
  const triggered = Object.entries(counts).filter(([,n]) => n >= 3).map(([cat]) => cat);
  return triggered.map(cat => DREAM_CATEGORIES[cat].combo);
}

