// คำนวณข้อมูลปีชงของปีที่ระบุ (yearBE) แบบสด ใช้ได้ทุกปีไม่มีวันหมดอายุ
function buildChongData(yearBE) {
  const curIndex = getZodiacIndex(yearBE);
  const result = {};
  for (const key in CHONG_OFFSETS) {
    const info = CHONG_OFFSETS[key];
    const zIndex = (curIndex + info.offset) % 12;
    const years = [];
    for (let y = yearBE; y >= yearBE - 100; y--) {
      if (getZodiacIndex(y) === zIndex) years.push(y);
    }
    result[key] = {
      ...info,
      zodiac: ZODIAC_TH[zIndex],
      emoji: ZODIAC_EMOJI[zIndex],
      desc: info.descTpl,
      years: years.reverse()
    };
  }
  return result;
}

function getChongType(birthYearBE, currentYearBE) {
  const data = buildChongData(currentYearBE);
  for (const key in data) {
    if (data[key].years.includes(birthYearBE)) return data[key];
  }
  return null;
}

